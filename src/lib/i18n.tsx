export type TranslationKey = keyof typeof dict.nl

// ─── Context + hooks ───────────────────────────────────────────

interface I18nApi {
  lang: Lang
  setLang: (l: Lang) => void
  t: (key: TranslationKey, vars?: Record<string, string | number>) => string
}

const I18nCtx = createContext<I18nApi | null>(null)

function interpolate(template: string, vars?: Record<string, string | number>): string {
  if (!vars) return template
  return template.replace(/\{(\w+)\}/g, (_, k) => (k in vars ? String(vars[k]) : `{${k}}`))
}

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>(() => {
    try {
      const stored = localStorage.getItem(STORAGE_KEY)
      if (stored === 'nl' || stored === 'en') return stored
    } catch { /* */ }
    return DEFAULT_LANG
  })

  useEffect(() => {
    try { localStorage.setItem(STORAGE_KEY, lang) } catch { /* */ }
    document.documentElement.lang = lang
  }, [lang])

  const setLang = useCallback((l: Lang) => setLangState(l), [])

  const t = useCallback<I18nApi['t']>(
    (key, vars) => {
      const tbl = dict[lang] as Record<string, string>
      const fallback = dict.nl as Record<string, string>
      const raw = tbl[key] ?? fallback[key] ?? key
      return interpolate(raw, vars)
    },
    [lang],
  )

  const value = useMemo<I18nApi>(() => ({ lang, setLang, t }), [lang, setLang, t])

  return <I18nCtx.Provider value={value}>{children}</I18nCtx.Provider>
}

export function useT() {
  const ctx = useContext(I18nCtx)
  if (!ctx) {
    // Fallback voor wanneer hook buiten provider gebruikt wordt (bv. PDF
    // pre-render context). Geeft de Nederlandse string terug zonder side
    // effects zodat de app niet crasht.
    return {
      lang: DEFAULT_LANG as Lang,
      setLang: () => { /* noop */ },
      t: (key: TranslationKey, vars?: Record<string, string | number>) =>
        interpolate((dict.nl as Record<string, string>)[key] ?? key, vars),
    }
  }
  return ctx
}

/**
 * Pure t() voor gebruik buiten React (bv. inline in PDF-generatie waar
 * we de lang als parameter krijgen).
 */
export function tFor(lang: Lang, key: TranslationKey, vars?: Record<string, string | number>): string {
  const tbl = (dict[lang] ?? dict.nl) as Record<string, string>
  const fallback = dict.nl as Record<string, string>
  return interpolate(tbl[key] ?? fallback[key] ?? key, vars)
}

